# 直接用大括號建立包含單一字串元素的集合
print('=' * 50)
set1 = {'Anastasia'} 
print(set1)  # 輸出: {'Anastasia'} (集合內只有 1 個長字串元素)
# 將字串傳入 set() 函式，字串會被拆解成單一字元，並自動剔除重複字元（如小寫 'a'）
set1 = set('Anastasia')
# 輸出: {'n', 't', 'i', 'a', 'A', 's'} (順序可能隨機，重複的 'a' 被去除了)
print(set1)  #{'n', 't', 'i', 'a', 'A', 's'}
# 將字典傳入 set() 函式，預設只會擷取字典的「鍵 (Key)」
set1 = set({'貓':'cat','狗':'dog'})
print(set1)  # 輸出: {'貓', '狗'}
# 將字串 '嘻嘻哈哈' 轉為集合，字串被拆成單字元並剔除重複字（'嘻' 與 '哈' 各留一個）
set1 = set('嘻嘻哈哈')
# 輸出: {'嘻', '哈'} (或 {'哈', '嘻'})
print(set1)  
# 使用 .add() 會將「笑嘻嘻」作為「一個完整的元素」加入集合
set1.add('笑嘻嘻')
# 輸出: {'嘻', '哈', '笑嘻嘻'}
print('=' * 20)
print(set1)  
# 使用 .remove() 移除指定的元素 '笑嘻嘻'
set1.remove('笑嘻嘻')
# 輸出: {'嘻', '哈'}
print(set1)  
# 使用 .discard() 嘗試移除 '笑嘻嘻'
# 因為在上一步已經移除掉了，但 .discard() 找不到元素時「不會報錯」，會安全地忽
set1.discard('笑嘻嘻')
# 使用 .update() 傳入字串 '笑嘻嘻'
# .update() 會把傳入的字串拆解成字元 ('笑', '嘻') 再分別加入，並剔除重複的 '嘻'
set1.update('笑嘻嘻')
# 輸出: {'嘻', '哈', '笑'}
print(set1) 
# 被註解掉的程式碼：若取消註解，因為目前集合內有 '笑嘻嘻' 拆開後的單字，但沒有完整的 '笑嘻嘻' 字串，執行會報 KeyError 錯誤
#set1.remove('笑嘻嘻')
# 使用 .pop() 隨機取出並移除集合中的「任意一個元素」
set1.pop() 
 
print(set1)