# 定義一個可以計算等差數列的和與末項的自定函式,呼叫函式前使用者須輸入數列的首項、公差、項數,呼叫函式後印出數列的和及數列的末項
# 定義計算平均值的函數
# 定義計算等差數列的末項與和的函數
def progress(a1, d, n):
  # 計算等差數列的末項與和
  an = a1 + (n-1) * d  # 末項
  # 計算等差數列的和
  sn = n * (a1 + an) / 2  # 和
  # 返回末項與和
  return an, sn
 
# 使用者輸入等差數列的首項、公差與項數
a1 = eval(input('輸入數列的首項：'))
# 使用者輸入等差數列的公差
d = eval(input('輸入數列的公差：'))
# 使用者輸入等差數列的項數
an = eval(input('輸入數列的項數：'))
# 計算等差數列的末項與和
an, sn = progress(a1, d, an)
# 輸出結果
print(f'等差數列的末項為 {an}，和為 {sn}', end = '')
