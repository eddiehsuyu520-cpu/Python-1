# 檢查大寫 'P' 是否在字串 'Python' 之中（結果為 True）
print('P' in 'Python')          

# 檢查小寫 'x' 是否不在字串 'Python' 之中（結果為 True）
print('x' not in 'Python')      

# 檢查數字 1 是否存在於 [1, 2, 3] 列表之中（結果為 True）
print(1 in [1, 2, 3])           

# 檢查數字 2 是否不存在於 [1, 2, 3] 列表之中（數字 2 其實在裡面，因此結果為 False）
print(2 not  in [1, 2, 3])    