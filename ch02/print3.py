# ── 1. 基礎整數與寬度、對齊控制 ─────────────────────────────
print(" ── 1. 基礎整數與寬度、對齊控制 ─────────────────────────────")

# 行 01：正常顯示整數，不做任何寬度修飾
print('[%d]' % (12345))        # 輸出: [12345]

# 行 02：設定寬度為 8。預設靠右對齊，寬度有剩時在左邊補 3 個空格
print('[%8d]' % (12345))       # 輸出: [   12345]

# 行 03：設定寬度為 8，加入減號「-」強制靠左對齊，寬度有剩時在右邊補空格
# 💡 注意：負號「-」本身也算一個字元長度，所以 -12345 佔了 6 格，右邊補 2 個空格
print('[%-8d]' % (-12345))     # 輸出: [-12345  ]


# ── 2. 補零與寬度不足應變 ──────────────────────────────────
print("\n ── 2. 補零與寬度不足應變 ──────────────────────────────────")

# 行 04：設定寬度為 8，加入「0」修飾字。寬度有剩時在左邊補 0 填滿
print('[%08d]' % (12345))      # 輸出: [00012345]

# 行 05：設定寬度為 3，但資料 (-12345) 實際長度高達 6 格。
# 💡 鐵律：寬度不足時直接「無視限制」，完整顯示全部數據，絕不截斷！
print('[%3d]' % (-12345))      # 輸出: [-12345]


# ── 3. 字元格式化與 ASCII 碼轉換 (%c) ──────────────────────
print("\n ── 3. 字元格式化與 ASCII 碼轉換 (%c) ──────────────────────")

# 行 06：顯示單一字元「A」
print('[%c]' % ('A'))          # 輸出: [A]

# 行 07：設定字元輸出寬度為 4。預設靠右對齊，左邊補 3 個空格
print('[%4c]' % ('A'))         # 輸出: [   A]

# 行 08：超經典！傳入數字 65。
# 💡 機制：%c 遇到整數時，會自動將其視為 ASCII 編碼，轉換為對應的字元（65 就是大寫 A）
print('[%c]' % (65))           # 輸出: [A]

# ── 4. 字串格式化與寬度控制 (%s) ─────────────────────────────
print(" ── 4. 字串格式化與寬度控制 (%s) ─────────────────────────────")

# 行 09：正常顯示字串資料，不做任何寬度修飾
print('[%s]' % ('ABCDE'))        # 輸出: [ABCDE]

# 行 10：設定寬度為 8。預設靠右對齊，寬度有剩時在左邊補 3 個空格
print('[%8s]' % ('ABCDE'))       # 輸出: [   ABCDE]

# 行 11：設定寬度為 3，但資料 ('ABCDE') 實際長度有 5 格。
# 💡 鐵律：單純設定寬度時，若寬度不足，一律無視限制完整顯示
print('[%3s]' % ('ABCDE'))       # 輸出: [ABCDE]


# ── 5. 字串的精確度修飾 (.位數) ──────────────────────────────
print("\n ── 5. 字串的精確度修飾 (.位數) ──────────────────────────────")

# 行 12：設定總寬度為 6，且加入「.2」限制只顯示 2 個字元。
# 💡 機制：'.2' 具有最高優先權，會強制將 'ABCDE' 截斷只留下前兩個字 'AB'。
# 接著再套用寬度 6 的規範：因為 'AB' 只有 2 格，所以在左邊補上 4 個空格來湊滿 6 格。
print('[%6.2s]' % ('ABCDE'))     # 輸出: [    AB]

# 補充對比：%-6.2s -> 設定總寬度 6，只取 2 字元，且「靠左對齊」
print('[%-6.2s]' % ('ABCDE'))    # 輸出: [AB    ]

