print(" ── 1. 整數轉浮點數 ──────────────────────────────────")
i1 = 10
# 使用 float() 函式將整數強制轉型為浮點數（會在尾巴補上 .0）
f1 = float(i1) 
# type(f1) 會顯示該變數的型態類別
print(i1, f1, type(f1))         # 輸出: 10 10.0 <class 'float'>


print("\n ── 2. 浮點數轉整數（無條件捨去小數） ───────────────────")
f2 = 1234.5678
# 使用 int() 函式將浮點數轉型為整數（直接砍掉所有小數點後面的數字，不做四捨五入）
i2 = int(f2) 
print(f2, i2, type(i2))         # 輸出: 1234.5678 1234 <class 'int'>

print("\n ── 3. 浮點數轉整數（四捨五入） ───────────────────────")
# 使用 round() 函式將浮點數四捨五入到最接近的整數
i3 = round(f2) 
print(f2, i3, type(i3))         # 輸出: 1234.5678 1235 <class 'int'>

print("\n ── 4. 數值轉字串 ──────────────────────────────────")
# 延續前面的 i2 = 1234
i2 = 1234  
# 使用 str() 函式將整數強制轉型為字串（前後會加上看不見的引號）
s = str(i2) 
# type(s) 會顯示 <class 'str'>
print(s, type(s))               # 輸出: 1234 <class 'str'>


# ── 5. 浮點數轉布林值 ────────────────────────────────
print("\n ── 5. 浮點數轉布林值 ────────────────────────────────")
# 延續前面的 f1 = 10.0
f1 = 10.0  
# 使用 bool() 函式將浮點數轉型為布林值（非零數字一律轉為 True）
b = bool(f1) 
# type(b) 會顯示 <class 'bool'>
print(b, type(b))               # 輸出: True <class 'bool'>