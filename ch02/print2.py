print(" ── 1. 插入字元與字串 (%c, %s) ──────────────────────────")
# %c 用來插入單一字元，%s 用來插入字串
# 後方的 % ('張', '無忌') 會依序填入前面的位置
print('%c%s 先生' % ('張', '無忌'))      # 輸出: 張無忌 先生

print("\n ── 2. 插入整數與浮點數 (%d, %f) ────────────────────────")
# 宣告整數變數 wt (重量) 與浮點數變數 price (單價)
wt, price = 3, 20.5

# %s 帶入字串 '香蕉'
# %d 帶入整數 wt (3)
# %f 帶入浮點數總價 wt * price (61.5)，預設會補滿到小數點後 6 位
print('%s%d 斤,共%f 元' % ('香蕉', wt, wt * price))  # 輸出: 香蕉 3 斤,共 61.500000 元