# ── 1. 基礎字串常值印出 ──────────────────────────────────
print(" ── 1. 基礎字串常值印出 ──────────────────────────────────")

# 行 01：直接將完整的固定文字當作字串常值（Literal）印出
print('汽水 2 打 24 瓶')        # 輸出: 汽水 2 打 24 瓶


# ── 2. 單一引數省略括號技巧 ──────────────────────────────
print("\n ── 2. 單一引數省略括號技巧 ──────────────────────────────")

# 行 02：使用 %d 舊式格式化填入數字
# 💡 機制：因為後方只需要填入數字 2 這一個引數，所以不需要寫成 % (2)，直接寫 %2 即可
print('汽水 %d 打 24 瓶' % 2)      # 輸出: 汽水 2 打 24 瓶

# 補充對比：當引數有兩個以上時，就「必須」強制加上小括號，否則 Python 會報錯
print('汽水 %d 打 %d 瓶' % (2, 24)) # 輸出: 汽水 2 打 24 瓶

# ── 3. 多重引數與變數運算式應用 ─────────────────────────────
print(" ── 3. 多重引數與變數運算式應用 ─────────────────────────────")

# 行 03：當引數有三個時，後面必須使用小括號 () 依序包覆（包含字串與兩個整數）
print('%s%d 打%d 瓶' % ('汽水', 2, 24))         # 輸出: 汽水2 打24 瓶


# 行 04：宣告變數 dozen（打數）為 2
dozen = 2

# 行 05：超實用！引數串列中同時包含「字串常值」、「變數」與「乘法運算式 (dozen * 12)」
# 💡 機制：Python 走到後面時，會先將 dozen * 12 算成 24，再將這三個最終結果依序填入前面
print('%s%d 打%d 瓶' % ('汽水', dozen, dozen * 12)) # 輸出: 汽水2 打24 瓶


#為了程式碼的可讀性（Readability）與安全性，現代專案中（如您的 Django 開發）大部份開發者在遇到單一變數時，會更傾向使用新一代的 f-string 寫法
print(f'汽水 {dozen} 打{dozen * 12} 瓶')