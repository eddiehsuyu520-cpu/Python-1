# ── 1. 進位制字首與寬度控制 ─────────────────────────────────
print(" ── 1. 進位制字首與寬度控制 ─────────────────────────────────")

# 行 01：加入修飾字「 # 」以十六進位顯示。自動在前方加上 0x 字首識別符
print('[%#x]' % 12345)          # 輸出: [0x3039]

# 行 02：設定總寬度為 8，並加入「 0 」修飾字。寬度有剩時在左邊補 0 填滿
print('[%08d]' % 12345)         # 輸出: [00012345]


# ── 2. 靠左對齊與正數保留空格 ───────────────────────────────
print("\n ── 2. 靠左對齊與正數保留空格 ───────────────────────────────")

# 行 03：設定總寬度為 8，加入減號「 - 」強制靠左對齊，寬度有剩時在右邊補空格
print('[%-8d]' % 12345)         # 輸出: [12345   ]

# 行 04：超進階！在 % 和 d 之間刻意「留一個空格」
# 💡 機制：當數值為「正數」時，會在前方強制預留一個空格位置；若為「負數」則正常顯示負號。
# 這樣可以讓正負數在上下並排印出時，數字的部分能夠完美對齊！
print('[% d]' % 12345)          # 輸出: [ 12345]

# 補充對比：如果傳入負數，空格修飾字會被負號自動覆蓋
print('[% d]' % -12345)         # 輸出: [-12345]
