# 宣告三個變數：b 為布林值、i 為整數、f 為浮點數
b, i, f = True, 2, 3.4

print(" ──  加法運算 ──────────────────────────────────")
# b + i -> 1 + 2 = 3 (bool 轉 int)
# b + f -> 1.0 + 3.4 = 4.4 (bool 轉 float)
# i + f -> 2.0 + 3.4 = 5.4 (int 轉 float)
print(b + i, b + f, i + f)          # 輸出: 3 4.4 5.4
print(type(b),type(i),type(f))

print(" ── 減法運算 ──────────────────────────────────")
# b - i -> 1 - 2 = -1
# b - f -> 1.0 - 3.4 = -2.4
# i - f -> 2.0 - 3.4 = -1.4
print(b - i, b - f, i - f)          # 輸出: -1 -2.4 -1.4
print(type(b),type(i),type(f))

print(" ── 乘法運算 ──────────────────────────────────")
# b * i -> 1 * 2 = 2
# b * f -> 1.0 * 3.4 = 3.4
# i * f -> 2.0 * 3.4 = 6.8
print(b * i, b * f, i * f)          # 輸出: 2 3.4 6.8
print(type(b),type(i),type(f))

print(" ── 除法運算 ──────────────────────────────────")
# Python 的單斜線除法 `/` 的結果「永遠是浮點數 (float)」
# b / i -> 1 / 2 = 0.5
# b / f -> 1.0 / 3.4 = 0.29411764705882354
# i / f -> 2.0 / 3.4 = 0.5882352941176471
print(b / i, b / f, i / f) 
print(type(b),type(i),type(f))