print(" ── 1. 基礎多重資料印出 ──────────────────────────────────")
# 顯示字串和浮點數常值（預設會用「一個空格」將兩者分開）
print('Python', 3.8)            # 輸出: Python 3.8


print("\n ── 2. 自訂分隔字串 sep ──────────────────────────────────")
# 將間隔字串設為逗號 ','
print('台北', '台中', '台南', sep=',')  # 輸出: 台北,台中,台南

# 將間隔字串設為跳格鍵 '\t'（Tab，會自動對齊並產生數個空格）
print('高雄', '屏東', sep='\t')       # 輸出: 高雄      屏東

print("\n ── 3. 自訂結尾字串 end ──────────────────────────────────")
# 將結尾字串設為空字串 ''，這會讓下一個 print() 的內容接在後面，不換行
print('價目表：', end='') 

money = 30
# 顯示 money 變數，並直接銜接在前一個 print 的後面印出
print('陽春麵', money, '元')     # 輸出: 價目表：陽春麵 30 元