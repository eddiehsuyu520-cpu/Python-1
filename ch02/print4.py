# ── 1. 浮點數預設位數與四捨五入 ─────────────────────────────
print(" ── 1. 浮點數預設位數與四捨五入 ─────────────────────────────")

# 行 01：正常顯示正浮點數，%f 預設一律補滿到小數點後 6 位
print('[%f]' % 12345.67)        # 輸出: [12345.670000]

# 行 02：正常顯示負浮點數，一樣補滿小數點後 6 位（負號算在數值本身）
print('[%f]' % -12.345)         # 輸出: [-12.345000]

# 行 03：使用 %.2f 限制小數 2 位。第 3 位小數為 5，觸發四捨五入進位
print('[%.2f]' % 12.345)        # 輸出: [12.35]


# ── 2. 浮點數總寬度與小數限制組合 ───────────────────────────
print("\n ── 2. 浮點數總寬度與小數限制組合 ───────────────────────────")

# 行 04：設定總寬度 8（包含負號與小數點），且限制小數 2 位。
# 資料 '-12.35' 長度為 6 格，因此預設靠右對齊並在左邊補 2 個空格
print('[%8.2f]' % -12.3456)     # 輸出: [  -12.35]

# 行 05：設定總寬度 3，限制小數 1 位。資料處理後為 '123.5'（長度 5 格）。
# 💡 鐵律：當總寬度設定不足（3 < 5）時，自動無視寬度限制，完整顯示資料
print('[%3.1f]' % 1234.567)     # 修正數值以完美對齊原廠 123.5 輸出結果
# 原廠範例：print('%3.1f'%123.45) 成果為 123.5


# ── 3. 使用 .0f 去除小數點與科學記號 ───────────────────────
print("\n ── 3. 使用 .0f 去除小數點與科學記號 ───────────────────────")

# 行 06：%.0f 代表「完全不要顯示小數點和小數」。第 1 位小數為 5，四捨五入到個位數。
# 總寬度設為 8，資料 '-1235' 長度為 5 格，左邊補 3 個空格
print('[%8.0f]' % -1234.56)     # 輸出: [   -1235]

# 行 07：與行 06 同理，正數 1234.56 經由 %.0f 變成 1235（長度 4 格）。
# 總寬度設為 8，左邊補 4 個空格
print('[%8.0f]' % 1234.56)      # 輸出: [    1235]

# 行 08：使用大寫 %E 輸出科學記號（預設小數 6 位）。小數第 7 位四捨五入。
print('[%E]' % 12345677.89)      # 輸出: [1.234568E+07]

# ── 4. 基礎科學記號與小數不足補零 (%e) ──────────────────────────
print(" ── 4. 基礎科學記號與小數不足補零 (%e) ──────────────────────────")

# 行 09：使用小寫 %e 輸出科學記號（123.4 轉為 1.234 x 10^2）
# 💡 機制：%e 預設小數位數是 6 位，如果原本的小數位數不足（此處只有3和4），後面會自動補 0 湊滿 6 位
print('[%e]' % 123.4)          # 輸出: [1.234000e+02]


# ── 5. 科學記號總寬度與小數位數控制組合 ─────────────────────────
print("\n ── 5. 科學記號總寬度與小數位數控制組合 ─────────────────────────")

# 行 10：大數值範例。設定總寬度 10，小數固定 2 位，使用小寫 e。
# '1.23e+04' 總長度為 8 格，因此預設靠右對齊，並在左邊補 2 個空格湊滿 10 格
print('[%10.2e]' % 12345.6)      # 輸出: [  1.23e+04]

# 行 11：極小值範例。設定總寬度 10，小數固定 2 位，使用大寫 E。
# 數值 0.000123456 轉為科學記號（1.23456 x 10^-4）。
# 經 '.2' 截斷四捨五入後為 '1.23E-04'（長度一樣是 8 格），預設靠右對齊，左邊補 2 個空格
print('[%10.2E]' % 0.000123456)  # 輸出: [  1.23E-04]
