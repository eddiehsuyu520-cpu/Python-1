# ── 1. 系統音與退格控制 (\a, \b) ─────────────────────────────
print(" ── 1. 系統音與退格控制 (\a, \b) ─────────────────────────────")

# 行 01：\a 代表 Alert（警告音）。印出文字的同時，電腦會發出一聲嗶聲
print('1234567890!\a')          # 輸出: 1234567890! (並有系統提示音)

# 行 02：\b 代表 Backspace（退格鍵 / 往回倒退一格）。
# 💡 機制：游標印完 5 之後倒退一格回到 5 的位置，接著印出 6，所以 5 就被 6 覆蓋掉了
print('12345\b67890!')         # 輸出: 123467890!


# ── 2. 換行與歸位控制 (\n, \r) ──────────────────────────────
print("\n ── 2. 換行與歸位控制  ──────────────────────────────")

# 行 03：\n 代表 Newline（換行）。游標直接跳到下一行的行首
print('1234567890!\n')          # 輸出: 1234567890! (下方會多出一個空行)

# 行 04：\r 代表 Carriage Return（歸位鍵 / 游標跳回當前行行首）。
# 💡 機制：印完 123 之後，\r 讓游標閃回最左邊，接下來印出的 4567890! 
# 會直接把原本在最左邊的 123 覆蓋掉（4覆蓋1, 5覆蓋2, 6覆蓋3）
print('123\r4567890!')         # 輸出: 4567890!


# ── 3. 跳格與符號還原 (\t, \\, \', \") ───────────────────────
print("\n ── 3. 跳格與符號還原 (\t, \\, \', \") ───────────────────────")

# 行 05：\t 代表 Tab（水平跳格）。會自動對齊並產生數個空格
print('123\t4567')             # 輸出: 123     4567

# 行 06：還原符號本身。
# \\ 會印出一個普通反斜線；\' 會印出單引號；\" 會印出雙引號
# 這樣可以防止 Python 誤以為引號是程式碼的結尾而報錯
print('12\\3\'45\"67')          # 輸出: 12\3'45"67
