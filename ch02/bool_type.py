b=False                 # 宣告 b 為布林變數，變數值為 False
print(type(b))          # 顯示布林變數 b 的類別         ⇨ <class 'bool'>
print(type(1))          # 顯示整數常值 1 的類別         ⇨ <class 'int'>
print(bool(1))          # 使用 bool 函式將 1 轉成布林值    ⇨ True
print(bool(-1))         # 使用 bool 函式將 -1 轉成布林值   ⇨ True
print(bool('Python'))   # 使用 bool 函式將 'Python' 轉成布林值 ⇨ True
c=None                  # 宣告 c 為 None 變數，變數值為 None
print(type(c))          # 顯示 None 變數 c 的類別        
print(bool(c))          # 使用 bool 函式將 None 轉成布林值 ⇨ False
d=""                    # 宣告 d 為字串變數，變數值為空字串
print(type(d))          # 顯示字串變數 d 的類別         
print(bool(d))          # 使用 bool 函式將空字串轉成布林
f=0                     # 宣告 f 為整數變數，變數值為 0
print(type(f))          # 顯示整數變數 f 的類別 
print(bool(f))          # 使用 bool 函式將整數 0 轉成布林值 ⇨ False 

