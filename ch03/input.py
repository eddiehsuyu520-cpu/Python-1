# ── 1. 接收字串與整數資料輸入 ──────────────────────────────
print(" ── 1. 接收字串與整數資料輸入 ──────────────────────────────")

# 💡 執行時提示：看到下方黑色終端機出現「請輸入姓名：」後，
# 必須用滑鼠點一下終端機，親自用鍵盤打字，打完後按一次 Enter 鍵！
userName = input('請輸入姓名：')

# 💡 執行時提示：按完 Enter 後，畫面會跳出下一個提示「請輸入年齡：」，
# 一樣輸入純數字後，再按一次 Enter 鍵！
# 這裡外層包了 int()，會自動把您打的文字轉成整數。
age = int(input('請輸入年齡：'))


# ── 2. 格式化綜合輸出與對齊 ──────────────────────────────
print("\n ── 2. 格式化綜合輸出與對齊 ──────────────────────────────")

# 使用 %s 帶入姓名、%d 帶入整數年齡，並利用 \t (Tab) 進行水平跳格對齊
print('[姓名：%s\t 年齡：%d 歲]' % (userName, age))
