# ── 1. 宣告字串變數與索引圖解 ──────────────────────────────
print(" ── 1. 宣告字串變數與索引圖解 ──────────────────────────────")
# 索引位置：012345 6 7891011 (總長度 12)
s = 'Python 基礎必修課'


# ── 2. 基礎正向切片練習 ──────────────────────────────────
print("\n ── 2. 基礎正向切片練習 ──────────────────────────────────")

# s[:] -> 開始與結束都省略，代表「從頭擷取到尾」，複製整段字串
print("s[:]   ->", [s[:]])      # 輸出: ['Python 基礎必修課']

# s[7:] -> 從索引 7（基）開始，結束省略，代表「擷取到字串結尾」
print("s[7:]  ->", [s[7:]])     # 輸出: ['基礎必修課']

# s[:6] -> 開始省略（從0開始），擷取到索引 6 之前（不含6，所以只拿 0~5）
print("s[:6]  ->", [s[:6]])     # 輸出: ['Python']

# s[5:8] -> 從索引 5（n）擷取到 8 之前（不含8，所以只拿 5, 6, 7）
# 💡 提示：索引 6 是空格，所以拿到的內容是 'n' + '空格' + '基'
print("s[5:8] ->", [s[5:8]])    # 輸出: ['n 基']


# ── 3. 進階步長與逆向切片（間隔參數） ─────────────────────────
print("\n ── 3. 進階步長與逆向切片（間隔參數） ─────────────────────────")

# s[9:6:-1] -> 間隔為 -1 代表「由右往左逆向擷取」。從 9（必）倒退擷取到 6 之前（不含6）
# 拿到的索引順序為 9(必)、8(礎)、7(基)
print("s[9:6:-1] ->", [s[9:6:-1]])  # 輸出: ['必礎基']

# s[::2] -> 從頭到尾，間隔 2 格跳著擷取（拿索引 0, 2, 4, 6, 8, 10）
print("s[::2]    ->", [s[::2]])     # 輸出: ['Pto 礎修']

# s[::-1] -> 超實用！從尾到頭、間隔 -1 擷取，直接將「整串文字反轉」
print("s[::-1]   ->", [s[::-1]])    # 輸出: ['課修必礎基 nohtyP']

# s[::-2] -> 從尾到頭逆向反轉，且間隔 2 格跳著擷取
print("s[::-2]   ->", [s[::-2]])    # 輸出: ['課必基 nhy']