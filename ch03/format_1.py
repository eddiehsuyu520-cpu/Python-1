# ── 1. 宣告字串與數值變數 ──────────────────────────────────
print(" ── 1. 宣告字串與數值變數 ──────────────────────────────────")
# 宣告商品名稱字串與價格整數
s1 = '電車月票'
s2 = 1280


# ── 2. 使用 format() 進行位置索引格式化 ──────────────────────
print("\n ── 2. 使用 format() 進行位置索引格式化 ──────────────────────")

# 💡 機制：.format(s1, s2) 傳入的引數索引從 0 開始數
# {0} 代表會被後面第一個引數 s1 ('電車月票') 替換
# {1} 代表會被後面第二個引數 s2 (1280) 替換
print('項目：{0}  金額：{1}元'.format(s1, s2)) # 輸出: 項目：電車月票  金額：1280元


# ── 3. (進階補充) 省略索引與重複引數技巧 ─────────────────────
print("\n ── 3. (進階補充) 省略索引與重複引數技巧 ─────────────────────")

# 技巧 A：如果順序剛好，大括號內的數字可以完全不寫，Python 會自動照順序填入
print('項目：{}  金額：{}元'.format(s1, s2))
# f-string（字串內嵌字元功能） 💡 關鍵：直接把變數寫在 {} 裡面，引號外面不需要再補變數
print(f"項目：{s1}  金額：{s2}元")  # 輸出: 項目：電車月票  金額：1280元

# 技巧 B：這是舊式 % 格式化辦不到的！同一個引數索引可以重複使用，甚至調換順序
print('【提示】確認購買{0}嗎？{0}的費用是{1}元，請扣款{1}元。'.format(s1, s2))