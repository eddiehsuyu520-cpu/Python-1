# ── 1. 宣告字串變數 ──────────────────────────────────
print(" ── 1. 宣告字串變數 ──────────────────────────────────")

# 宣告字串變數，長度總共有 11 個字元（索引範圍為 0 到 10）
# P(0) y(1) t(2) h(3) o(4) n(5)  (6) 基(7) 礎(8) 必(9) 修(10) 課(11) -> 修正：字串實際長度為 12 個字元，索引 0~11
# 注意：中間的「空格」也算一個獨立的字元！
s1 = 'Python 基礎必修課'


# ── 2. 正向與逆向索引讀取 ──────────────────────────────
print("\n ── 2. 正向與逆向索引讀取 ──────────────────────────────")

# 行 02：正向索引從 0 開始數。s1[3] 代表第 4 個字元
print('正向索引 s1[3]  :', s1[3])     # 輸出: h

# 行 03：逆向索引從 -1 開始由右往左數。s1[-2] 代表倒數第 2 個字元
print('逆向索引 s1[-2] :', s1[-2])    # 輸出: 修


# ── 3. 索引越界崩潰陷阱 (IndexError) ────────────────────
print("\n ── 3. 索引越界崩潰陷阱 (IndexError) ────────────────────")

# 行 04：這個字串的最大正向索引只到 11（課）。
