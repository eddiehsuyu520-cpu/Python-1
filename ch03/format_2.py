str1 = '張三'
num1 = 17

# 在 format() 中，'name=' 和 'age=' 就是「具名參數」（傳入時指定了名字）
# 字串中的大括號 {name} 和 {age} 會精準對應到相同名稱的具名參數
# 這種寫法的好處是：大括號的順序與後面參數的傳入順序無關，易讀性極高
print('我是{name}今年{age}歲'.format(name = str1, age = num1))

#f-string（格式化字串字面值）是 Python 3.6 之後推出的新語法，它完全可以取代「具名參數」的 format() 寫法，且程式碼更簡短、更好讀。
# 直接在字串開頭加上 f，並把變數名稱直接塞進大括號中
print(f'我是{str1}今年{num1}歲')
